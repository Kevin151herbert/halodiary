// PayPal sandbox: vault (save PayPal once), authorize, capture, void, refund, payouts, webhooks.
// When credentials are missing, callers fall back to simulated mode and label it in the UI.

import {
  ApiError,
  type CheckoutPaymentIntent,
  Client,
  Environment,
  type ExperienceContextShippingPreference,
  OrdersController,
  PaymentsController,
  SubscriptionsController,
  type PaypalPaymentTokenCustomerType,
  type PaypalPaymentTokenUsageType,
  VaultController,
  type VaultInstructionAction,
  type VaultTokenRequestType,
} from "@paypal/paypal-server-sdk";

const BASE = process.env.PAYPAL_ENV === "live" ? "https://api-m.paypal.com" : "https://api-m.sandbox.paypal.com";

export function paypalConfigured() {
  return Boolean(process.env.PAYPAL_CLIENT_ID && process.env.PAYPAL_CLIENT_SECRET);
}

let cached: { token: string; expires: number } | null = null;

export async function accessToken() {
  if (cached && cached.expires > Date.now() + 60_000) return cached.token;
  const auth = Buffer.from(`${process.env.PAYPAL_CLIENT_ID}:${process.env.PAYPAL_CLIENT_SECRET}`).toString("base64");
  const res = await fetch(`${BASE}/v1/oauth2/token`, {
    signal: AbortSignal.timeout(15_000),
    method: "POST",
    headers: { Authorization: `Basic ${auth}`, "Content-Type": "application/x-www-form-urlencoded" },
    body: "grant_type=client_credentials",
    cache: "no-store",
  });
  if (!res.ok) throw new Error(`PayPal auth failed (${res.status})`);
  const json = (await res.json()) as { access_token: string; expires_in: number };
  cached = { token: json.access_token, expires: Date.now() + json.expires_in * 1000 };
  return cached.token;
}

async function call<T>(path: string, body?: unknown, method = "POST"): Promise<T> {
  const token = await accessToken();
  const res = await fetch(`${BASE}${path}`, {
    signal: AbortSignal.timeout(15_000),
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      "PayPal-Request-Id": crypto.randomUUID(),
      Prefer: "return=representation",
    },
    body: body ? JSON.stringify(body) : undefined,
    cache: "no-store",
  });
  const text = await res.text();
  const json = text ? JSON.parse(text) : {};
  if (!res.ok) {
    const detail = json?.details?.[0]?.description || json?.message || res.statusText;
    throw new Error(`PayPal ${path} failed: ${detail}`);
  }
  return json as T;
}


// Orders, payments and vault calls go through PayPal's official Server SDK (generated by APIMatic).
// Payouts and webhook verification are not in the SDK yet, so they use the REST API directly.
let sdk: { orders: OrdersController; payments: PaymentsController; vault: VaultController; subscriptions: SubscriptionsController } | null = null;
function client() {
  if (sdk) return sdk;
  const c = new Client({
    clientCredentialsAuthCredentials: { oAuthClientId: process.env.PAYPAL_CLIENT_ID!, oAuthClientSecret: process.env.PAYPAL_CLIENT_SECRET! },
    environment: process.env.PAYPAL_ENV === "live" ? Environment.Production : Environment.Sandbox,
    timeout: 20000,
  });
  sdk = { orders: new OrdersController(c), payments: new PaymentsController(c), vault: new VaultController(c), subscriptions: new SubscriptionsController(c) };
  return sdk;
}

/** Turn an SDK error into one readable line. */
async function sdkCall<T>(label: string, fn: () => Promise<{ result: T }>) {
  try {
    return (await fn()).result;
  } catch (e) {
    if (e instanceof ApiError) {
      const body = typeof e.body === "string" ? safeJson(e.body) : e.body;
      const detail = (body as { details?: { description?: string }[]; message?: string })?.details?.[0]?.description || (body as { message?: string })?.message;
      throw new Error(`PayPal ${label} failed: ${detail || e.statusCode}`);
    }
    throw e;
  }
}
const safeJson = (s: string) => {
  try {
    return JSON.parse(s);
  } catch {
    return {};
  }
};
const sdkMoney = (amount: number, currency: string) => ({ currencyCode: currency, value: amount.toFixed(2) });

/** Step 1 of saving PayPal: a setup token the payer approves once. */
export async function createSetupToken(opts: { capText: string; returnUrl: string; cancelUrl: string }) {
  const json = await sdkCall("setup token", () =>
    client().vault.createSetupToken({
      paypalRequestId: crypto.randomUUID(),
      body: {
        paymentSource: {
          paypal: {
            description: `HaloDiary monthly services budget: ${opts.capText}. Charged per visit, only after each visit is confirmed.`,
            usageType: "MERCHANT" as PaypalPaymentTokenUsageType,
            customerType: "CONSUMER" as PaypalPaymentTokenCustomerType,
            permitMultiplePaymentTokens: false,
            experienceContext: {
              brandName: "HaloDiary",
              shippingPreference: "NO_SHIPPING" as ExperienceContextShippingPreference,
              vaultInstruction: "ON_PAYER_APPROVAL" as VaultInstructionAction,
              returnUrl: opts.returnUrl,
              cancelUrl: opts.cancelUrl,
            },
          },
        },
      },
    }),
  );
  const approveUrl = json.links?.find((l) => l.rel === "approve")?.href;
  if (!approveUrl || !json.id) throw new Error("PayPal did not return an approval link");
  return { id: json.id, approveUrl };
}

/** Step 2: exchange the approved setup token for a reusable payment token. */
export async function createPaymentToken(setupTokenId: string) {
  const json = await sdkCall("payment token", () =>
    client().vault.createPaymentToken({
      paypalRequestId: crypto.randomUUID(),
      body: { paymentSource: { token: { id: setupTokenId, type: "SETUP_TOKEN" as VaultTokenRequestType } } },
    }),
  );
  return { paymentToken: json.id!, email: json.paymentSource?.paypal?.emailAddress ?? null };
}

/** Hold money for a confirmed visit: an AUTHORIZE order paid with the saved PayPal account. */
export async function authorizeWithVault(opts: { paymentToken: string; amount: number; currency: string; description: string; visitId: string }) {
  const order = await sdkCall("order", () =>
    client().orders.createOrder({
      paypalRequestId: crypto.randomUUID(),
      prefer: "return=representation",
      body: {
        intent: "AUTHORIZE" as CheckoutPaymentIntent,
        purchaseUnits: [
          {
            referenceId: opts.visitId.slice(0, 256),
            customId: opts.visitId.slice(0, 127),
            description: opts.description.slice(0, 127),
            amount: sdkMoney(opts.amount, opts.currency),
          },
        ],
        paymentSource: { paypal: { vaultId: opts.paymentToken } },
      },
    }),
  );
  let authId = order.purchaseUnits?.[0]?.payments?.authorizations?.[0]?.id;
  if (!authId) {
    const authorized = await sdkCall("authorize", () =>
      client().orders.authorizeOrder({ id: order.id!, paypalRequestId: crypto.randomUUID(), prefer: "return=representation" }),
    );
    authId = authorized.purchaseUnits?.[0]?.payments?.authorizations?.[0]?.id;
  }
  if (!authId) throw new Error("PayPal did not return an authorization");
  return { orderId: order.id!, authorizationId: authId };
}

/** Charge a hold. A partial final capture releases the rest. */
export async function captureAuthorization(authorizationId: string, partial?: { amount: number; currency: string }) {
  const json = await sdkCall("capture", () =>
    client().payments.captureAuthorizedPayment({
      authorizationId,
      paypalRequestId: crypto.randomUUID(),
      prefer: "return=representation",
      body: { finalCapture: true, ...(partial ? { amount: sdkMoney(partial.amount, partial.currency) } : {}) },
    }),
  );
  return json.id!;
}

export async function voidAuthorization(authorizationId: string) {
  await sdkCall("void", () => client().payments.voidPayment({ authorizationId, paypalRequestId: crypto.randomUUID() }));
}

/** Refund all or part of a charge (problem reports). */
export async function refundCapture(captureId: string, amount: number, currency: string, note: string) {
  const json = await sdkCall("refund", () =>
    client().payments.refundCapturedPayment({
      captureId,
      paypalRequestId: crypto.randomUUID(),
      prefer: "return=representation",
      body: { amount: sdkMoney(amount, currency), noteToPayer: note.slice(0, 255) },
    }),
  );
  return json.id!;
}

/** A monthly billing plan for one HaloDiary service at a fixed price. */
export async function createMonthlyPlan(opts: { productId: string; name: string; amount: number; currency: string }) {
  const plan = await sdkCall("billing plan", () =>
    client().subscriptions.createBillingPlan({
      paypalRequestId: crypto.randomUUID(),
      prefer: "return=representation",
      body: {
        productId: opts.productId,
        name: opts.name.slice(0, 127),
        billingCycles: [
          {
            frequency: { intervalUnit: "MONTH" as never, intervalCount: 1 },
            tenureType: "REGULAR" as never,
            sequence: 1,
            totalCycles: 0,
            pricingScheme: { fixedPrice: sdkMoney(opts.amount, opts.currency) },
          },
        ],
        paymentPreferences: { autoBillOutstanding: true, paymentFailureThreshold: 2 },
      },
    }),
  );
  return plan.id!;
}

/** Start a subscription; the payer approves it on PayPal. */
export async function createSubscription(opts: { planId: string; customId: string; returnUrl: string; cancelUrl: string }) {
  const sub = await sdkCall("subscription", () =>
    client().subscriptions.createSubscription({
      paypalRequestId: crypto.randomUUID(),
      prefer: "return=representation",
      body: {
        planId: opts.planId,
        customId: opts.customId.slice(0, 127),
        applicationContext: {
          brandName: "HaloDiary",
          shippingPreference: "NO_SHIPPING" as ExperienceContextShippingPreference,
          userAction: "SUBSCRIBE_NOW" as never,
          returnUrl: opts.returnUrl,
          cancelUrl: opts.cancelUrl,
        },
      },
    }),
  );
  const approveUrl = sub.links?.find((l) => l.rel === "approve")?.href;
  if (!sub.id || !approveUrl) throw new Error("PayPal did not return a subscription approval link");
  return { id: sub.id, approveUrl };
}

export async function getSubscriptionStatus(id: string) {
  const sub = await sdkCall("subscription status", () => client().subscriptions.getSubscription({ id }));
  return String(sub.status ?? "");
}

export async function cancelSubscription(id: string, reason: string) {
  await sdkCall("cancel subscription", () => client().subscriptions.cancelSubscription({ id, body: { reason: reason.slice(0, 127) } }));
}

/** A short-lived token the browser uses to start the PayPal JS SDK v6 (never the API secret). */
export async function browserClientToken(host: string) {
  const auth = Buffer.from(`${process.env.PAYPAL_CLIENT_ID}:${process.env.PAYPAL_CLIENT_SECRET}`).toString("base64");
  const params = new URLSearchParams({ grant_type: "client_credentials", response_type: "client_token", intent: "sdk_init" });
  params.append("domains[]", host.replace(/:\d+$/, ""));
  const res = await fetch(`${BASE}/v1/oauth2/token`, {
    signal: AbortSignal.timeout(15_000),
    method: "POST",
    headers: { Authorization: `Basic ${auth}`, "Content-Type": "application/x-www-form-urlencoded" },
    body: params.toString(),
    cache: "no-store",
  });
  const json = (await res.json()) as { access_token?: string; error_description?: string };
  if (!res.ok || !json.access_token) throw new Error(`PayPal client token failed: ${json.error_description ?? res.status}`);
  return json.access_token;
}

/** Check that a webhook really came from PayPal. */
export async function verifyWebhook(headers: Headers, body: unknown) {
  const webhookId = process.env.PAYPAL_WEBHOOK_ID;
  if (!webhookId) return false;
  const res = await call<{ verification_status: string }>("/v1/notifications/verify-webhook-signature", {
    auth_algo: headers.get("paypal-auth-algo"),
    cert_url: headers.get("paypal-cert-url"),
    transmission_id: headers.get("paypal-transmission-id"),
    transmission_sig: headers.get("paypal-transmission-sig"),
    transmission_time: headers.get("paypal-transmission-time"),
    webhook_id: webhookId,
    webhook_event: body,
  });
  return res.verification_status === "SUCCESS";
}

/** Pay the provider their share after a visit is done. */
export async function payout(opts: { receiver: string; amount: number; currency: string; note: string }) {
  const json = await call<{ batch_header: { payout_batch_id: string } }>("/v1/payments/payouts", {
    sender_batch_header: {
      sender_batch_id: `halodiary-${Date.now()}-${Math.floor(Math.random() * 1e6)}`,
      email_subject: "You have a HaloDiary payout",
    },
    items: [
      {
        recipient_type: "EMAIL",
        receiver: opts.receiver,
        amount: { currency: opts.currency, value: opts.amount.toFixed(2) },
        note: opts.note,
      },
    ],
  });
  return json.batch_header.payout_batch_id;
}

/**
 * Pay a provider their share. Uses the provider's PayPal email, else PAYPAL_PAYOUT_RECEIVER, else a sandbox
 * address that leaves the payout unclaimed (still a real Payouts batch). Never throws: a failure is reported
 * so the ledger records the payout as simulated instead of pretending it went through PayPal.
 */
export async function payProvider(opts: { providerEmail?: string | null; amount: number; currency: string; note: string; fallbackRef: string }) {
  if (!paypalConfigured() || opts.amount <= 0) return { ref: opts.fallbackRef, mode: "simulated" as const, error: null };
  const receiver = opts.providerEmail || process.env.PAYPAL_PAYOUT_RECEIVER || "provider-payouts@halodiary.example";
  try {
    const ref = await payout({ receiver, amount: opts.amount, currency: opts.currency, note: opts.note });
    return { ref, mode: "paypal_sandbox" as const, error: null };
  } catch (e) {
    return { ref: opts.fallbackRef, mode: "simulated" as const, error: String(e instanceof Error ? e.message : e).slice(0, 300) };
  }
}

/** Recent transactions for the assistant's spend questions (requires transaction search on the app). */
export async function listTransactions(startIso: string, endIso: string) {
  const qs = new URLSearchParams({ start_date: startIso, end_date: endIso, fields: "transaction_info" });
  return call<{ transaction_details?: unknown[] }>(`/v1/reporting/transactions?${qs}`, undefined, "GET");
}
